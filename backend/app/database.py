
from contextlib import contextmanager
import sqlite3

import psycopg
from psycopg import conninfo
from psycopg.rows import dict_row

from .config import DATABASE_PATH, DATABASE_URL


class PostgresAdapter:
    """Adapt existing SQLite-style queries to PostgreSQL."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        query = query.replace("?", "%s")
        return self.connection.execute(query, params)


@contextmanager
def get_db():
    if DATABASE_URL:
        connection_string = conninfo.make_conninfo(
            DATABASE_URL,
            sslmode="require",
            connect_timeout=10,
        )
        conn = psycopg.connect(
            connection_string,
            row_factory=dict_row,
        )
        try:
            yield PostgresAdapter(conn)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()
    else:
        DATABASE_PATH.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(DATABASE_PATH, timeout=15)
        conn.row_factory = sqlite3.Row
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()


def init_db():
    with get_db() as db:
        if DATABASE_URL:
            db.execute("""
                CREATE TABLE IF NOT EXISTS products (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    url TEXT NOT NULL,
                    target_price DOUBLE PRECISION,
                    current_price DOUBLE PRECISION,
                    currency TEXT NOT NULL DEFAULT 'INR',
                    last_checked TEXT,
                    last_error TEXT,
                    created_at TEXT NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS price_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    product_id BIGINT NOT NULL REFERENCES products(id)
                        ON DELETE CASCADE,
                    price DOUBLE PRECISION NOT NULL,
                    checked_at TEXT NOT NULL,
                    source TEXT NOT NULL DEFAULT 'page'
                )
            """)
        else:
            db.execute("""
                CREATE TABLE IF NOT EXISTS products (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    title TEXT NOT NULL,
                    url TEXT NOT NULL,
                    target_price REAL,
                    current_price REAL,
                    currency TEXT NOT NULL DEFAULT 'INR',
                    last_checked TEXT,
                    last_error TEXT,
                    created_at TEXT NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS price_history (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    product_id INTEGER NOT NULL,
                    price REAL NOT NULL,
                    checked_at TEXT NOT NULL,
                    source TEXT NOT NULL DEFAULT 'page',
                    FOREIGN KEY(product_id) REFERENCES products(id)
                        ON DELETE CASCADE
                )
            """)

        db.execute("""
            CREATE INDEX IF NOT EXISTS idx_history_product_time
            ON price_history(product_id, checked_at)
        """)
