
import os
import sqlite3
import sys
import psycopg
from app.config import DATABASE_PATH

url = os.environ.get("DATABASE_URL", "").strip()
if not url.startswith(("postgresql://", "postgres://")):
    sys.exit("DATABASE_URL is missing. Set it before migrating.")

source = sqlite3.connect(DATABASE_PATH)
source.row_factory = sqlite3.Row
try:
    products = [dict(row) for row in source.execute(
        "SELECT * FROM products ORDER BY id"
    )]
    history = [dict(row) for row in source.execute(
        "SELECT * FROM price_history ORDER BY id"
    )]
finally:
    source.close()

print(f"Source: {len(products)} products, {len(history)} history records")

with psycopg.connect(url, connect_timeout=15) as conn:
    with conn.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                url TEXT NOT NULL,
                target_price DOUBLE PRECISION,
                current_price DOUBLE PRECISION,
                currency TEXT NOT NULL DEFAULT 'INR',
                last_checked TEXT,
                last_error TEXT,
                created_at TEXT NOT NULL
            )
        """)
        cur.execute("""
            CREATE TABLE IF NOT EXISTS price_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
                price DOUBLE PRECISION NOT NULL,
                checked_at TEXT NOT NULL,
                source TEXT NOT NULL DEFAULT 'page'
            )
        """)
        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_history_product_time
            ON price_history(product_id, checked_at)
        """)

        cur.execute("SELECT COUNT(*) FROM products")
        if cur.fetchone()[0] != 0:
            raise RuntimeError(
                "Supabase products table is not empty. Migration stopped safely."
            )

        for p in products:
            cur.execute("""
                INSERT INTO products
                (id, title, url, target_price, current_price, currency,
                 last_checked, last_error, created_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
            """, (
                p["id"], p["title"], p["url"], p["target_price"],
                p["current_price"], p["currency"], p["last_checked"],
                p["last_error"], p["created_at"]
            ))

        for h in history:
            cur.execute("""
                INSERT INTO price_history
                (id, product_id, price, checked_at, source)
                VALUES (%s, %s, %s, %s, %s)
            """, (
                h["id"], h["product_id"], h["price"],
                h["checked_at"], h["source"]
            ))

        cur.execute("""
            SELECT setval(
                pg_get_serial_sequence('products', 'id'),
                COALESCE((SELECT MAX(id) FROM products), 1),
                EXISTS(SELECT 1 FROM products)
            )
        """)
        cur.execute("""
            SELECT setval(
                pg_get_serial_sequence('price_history', 'id'),
                COALESCE((SELECT MAX(id) FROM price_history), 1),
                EXISTS(SELECT 1 FROM price_history)
            )
        """)

        cur.execute("SELECT COUNT(*) FROM products")
        product_count = cur.fetchone()[0]
        cur.execute("SELECT COUNT(*) FROM price_history")
        history_count = cur.fetchone()[0]

        if product_count != len(products) or history_count != len(history):
            raise RuntimeError("Record count verification failed.")

print(
    f"SUCCESS: {product_count} products and "
    f"{history_count} history records copied to Supabase."
)
